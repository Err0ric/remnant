#!/usr/bin/env python3
"""Write docs/api.md from the server's own OpenAPI spec, so the reference cannot drift.

cd backend && uv run python ../scripts/apidoc.py            # rewrite docs/api.md
cd backend && uv run python ../scripts/apidoc.py --check    # exit 1 if it is stale
"""

# ruff: noqa: E501  # the intro is Markdown table rows, one per line

from __future__ import annotations

import argparse
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "api.md"
METHODS = ("get", "post", "put", "patch", "delete")

INTRO = """# API reference

<!-- Generated by scripts/apidoc.py from the server's OpenAPI spec. Do not edit by hand. -->

Everything the web UI does goes through this JSON API under `/api`. The machine-readable
spec is served at `GET /api/openapi.json`; import it into Postman, Insomnia, or Bruno.

## Calling it

| | |
|---|---|
| Authentication | `Authorization: Bearer <token>`. Create a token on your account page (**CLI and API tokens**); it carries your role and source access and can be revoked there. Browsers use the session cookie plus an `X-CSRF-Token` header on every non-GET request instead |
| Loopback installs with no accounts | No token needed |
| Errors | Non-2xx responses are `{"detail": "...", "code": "..."}`; `code` is stable, `detail` is for people |
| Rate limits | Sign-in, link redemption, and single sign-on starts are limited per address; `429` carries `Retry-After` |
| Audit | Every query, export, sign-in, admin change, and AI call is written to the audit log under the caller |
| Read-only queries | `POST /api/query` accepts `SELECT` and `WITH` only, through the server's guard, over the sources you may read |

```bash
curl -s https://siem.example.internal:8080/api/query \\
  -H "Authorization: Bearer $TOKEN" -H "Content-Type: application/json" \\
  -d '{"sql": "SELECT device_hostname, count(*) FROM events GROUP BY 1", "start": "2026-10-12T00:00:00Z"}'
```

The `remnant` command-line client wraps the same API (`remnant query ... -o json`), and reads
`REMNANT_SERVER` and `REMNANT_TOKEN` from the environment for scripts.

## Endpoints
"""


def _ref(schema: dict[str, Any], components: dict[str, Any]) -> dict[str, Any]:
    ref = schema.get("$ref")
    if ref:
        return dict(components.get(ref.rsplit("/", 1)[-1], {}))
    return schema


def _type(schema: dict[str, Any], components: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        parts = [_type(s, components) for s in schema["anyOf"] if s.get("type") != "null"]
        return " or ".join(dict.fromkeys(parts)) or "any"
    if "enum" in schema:
        return " | ".join(f"`{v}`" for v in schema["enum"])
    if "const" in schema:
        return f"`{schema['const']}`"
    kind = schema.get("type", "any")
    if kind == "array":
        return f"list of {_type(schema.get('items', {}), components)}"
    if kind == "string" and schema.get("format"):
        return str(schema["format"])
    return str(kind)


def _body(op: dict[str, Any], components: dict[str, Any]) -> str:
    content = op.get("requestBody", {}).get("content", {})
    if not content:
        return ""
    media, spec = next(iter(content.items()))
    if media != "application/json":
        return f"`{media}`"
    schema = _ref(spec.get("schema", {}), components)
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    fields = [
        f"`{name}`{'' if name in required else '?'}: {_type(prop, components)}"
        for name, prop in props.items()
    ]
    return "<br>".join(fields)


def _query(op: dict[str, Any], components: dict[str, Any]) -> str:
    params = [p for p in op.get("parameters", []) if p.get("in") == "query"]
    return "<br>".join(
        f"`?{p['name']}`{'' if p.get('required') else ' (optional)'}: "
        f"{_type(p.get('schema', {}), components)}"
        for p in params
    )


def _summary(op: dict[str, Any]) -> str:
    text = (op.get("description") or "").strip().split("\n\n")[0].replace("\n", " ")
    return text or str(op.get("summary", ""))


def render(spec: dict[str, Any]) -> str:
    components = spec.get("components", {}).get("schemas", {})
    by_tag: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, ops in sorted(spec["paths"].items()):
        for method in METHODS:
            if method in ops:
                tag = (ops[method].get("tags") or ["other"])[0]
                by_tag.setdefault(tag, []).append((method.upper(), path, ops[method]))
    lines = [INTRO]
    for tag in sorted(by_tag):
        lines.append(f"### {tag.capitalize()}\n")
        lines.append("| Method | Path | What it does | Query | JSON body (`?` optional) |")
        lines.append("|---|---|---|---|---|")
        for method, path, op in by_tag[tag]:
            cells = [
                f"`{method}`",
                f"`{path}`",
                _summary(op),
                _query(op, components),
                _body(op, components),
            ]
            lines.append("| " + " | ".join(c.replace("|", "\\|") for c in cells) + " |")
        lines.append("")
    return "\n".join(lines).rstrip("\n").replace("\\|", "&#124;") + "\n"


def build() -> str:
    sys.path.insert(0, str(ROOT / "backend"))
    from app.core.config import load_config
    from app.main import create_app

    with tempfile.TemporaryDirectory() as tmp:
        app = create_app(load_config(Path("missing.yaml"), {"APP__PATHS__DATA_DIR": tmp}))
        return render(app.openapi())


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    p.add_argument("--check", action="store_true", help="Fail if docs/api.md is out of date")
    args = p.parse_args(argv)
    text = build()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/api.md is out of date: run scripts/apidoc.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
